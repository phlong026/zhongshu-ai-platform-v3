package cn.iocoder.yudao.module.platform.wallet.orgpoint;

import cn.iocoder.yudao.module.infra.zhongshu.audit.AuditEventMessage;
import cn.iocoder.yudao.module.infra.zhongshu.audit.AuditPort;
import cn.iocoder.yudao.module.infra.zhongshu.audit.JdbcAuditPort;
import cn.iocoder.yudao.module.platform.test.PlatformPgIntegrationTest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;
import org.springframework.transaction.PlatformTransactionManager;

import javax.sql.DataSource;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;

@Import({OrgPointService.class, OrgPointPriceService.class, JdbcAuditPort.class})
@TestPropertySource(properties = "platform.test.extra-flyway-locations=,classpath:db/migration/platform-wallet")
class OrgPointAuditIntegrationTest extends PlatformPgIntegrationTest {

    @Autowired private DataSource dataSource;
    @Autowired private PlatformTransactionManager transactionManager;
    @Autowired private OrgPointService service;
    @Autowired private AuditPort auditPort;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS audit_event (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  event_type VARCHAR(64) NOT NULL,
                  actor_type VARCHAR(32) NOT NULL,
                  actor_id VARCHAR(64),
                  action VARCHAR(64) NOT NULL,
                  biz_type VARCHAR(64),
                  biz_id VARCHAR(64),
                  result VARCHAR(16) NOT NULL DEFAULT 'SUCCESS',
                  detail JSONB,
                  tenant_id BIGINT NOT NULL DEFAULT 0,
                  create_time TIMESTAMPTZ NOT NULL DEFAULT now()
                )
                """);
        jdbc.execute("TRUNCATE audit_event, org_member_quota, org_member_permission");
    }

    @Test
    void mockContractReceivesOperatorOrganizationTargetAndPreviousValue() {
        AuditPort mockAudit = mock(AuditPort.class);
        OrgPointService isolated = new OrgPointService(dataSource, transactionManager, mockAudit,
                new OrgPointPriceService(dataSource, transactionManager));
        isolated.setMemberPermission(7101L, 7201L, List.of("copy"), 7301L);
        isolated.setMemberPermission(7101L, 7201L, List.of("copy", "digital"), 7301L);

        ArgumentCaptor<AuditEventMessage> messages = ArgumentCaptor.forClass(AuditEventMessage.class);
        verify(mockAudit, org.mockito.Mockito.times(2)).record(messages.capture());
        AuditEventMessage update = messages.getAllValues().get(1);
        assertThat(update.getEventType()).isEqualTo("ORG_MEMBER_PERMISSION");
        assertThat(update.getActorType()).isEqualTo(AuditEventMessage.ActorType.ADMIN);
        assertThat(update.getActorId()).isEqualTo("7301");
        assertThat(update.getAction()).isEqualTo("SET");
        assertThat(update.getDetail()).containsEntry("orgId", 7101L)
                .containsEntry("targetUserId", 7201L)
                .containsEntry("allowedSubjects", List.of("copy", "digital"))
                .containsEntry("previousAllowedSubjects", List.of("copy"));
    }

    @Test
    void applicationContextInjectsJdbcAuditPortAndPersistsConfigurationAudit() {
        assertThat(auditPort).isInstanceOf(JdbcAuditPort.class);

        service.setMemberPermission(7401L, 7501L, List.of("copy", "digital"), 7601L);

        var row = jdbc.queryForMap("SELECT event_type, actor_type, actor_id, action, biz_type, biz_id, "
                + "result, detail::text AS detail, tenant_id FROM audit_event");
        assertThat(row).containsEntry("event_type", "ORG_MEMBER_PERMISSION")
                .containsEntry("actor_type", "ADMIN")
                .containsEntry("actor_id", "7601")
                .containsEntry("action", "SET")
                .containsEntry("biz_type", "org_member_permission")
                .containsEntry("biz_id", "7401:7501")
                .containsEntry("result", "SUCCESS")
                .containsEntry("tenant_id", 0L);
        assertThat((String) row.get("detail")).contains("allowedSubjects", "copy", "digital",
                "orgId", "7401", "targetUserId", "7501");
    }

    @Test
    void auditFailureRollsBackPermissionSetAndClear() {
        AuditPort failingAudit = mock(AuditPort.class);
        doThrow(new IllegalStateException("audit unavailable")).when(failingAudit).record(any());
        OrgPointService isolated = new OrgPointService(dataSource, transactionManager, failingAudit,
                new OrgPointPriceService(dataSource, transactionManager));

        assertThatThrownBy(() -> isolated.setMemberPermission(
                7701L, 7801L, List.of("copy"), 7901L))
                .isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM org_member_permission WHERE org_id=7701",
                Integer.class)).isZero();

        jdbc.update("INSERT INTO org_member_permission(id,org_id,user_id,allowed_subjects) VALUES (?,?,?,?)",
                8001L, 7701L, 7801L, "[\"copy\"]");
        assertThatThrownBy(() -> isolated.clearMemberPermission(7701L, 7801L, 7901L))
                .isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT allowed_subjects FROM org_member_permission "
                + "WHERE org_id=7701 AND user_id=7801", String.class)).isEqualTo("[\"copy\"]");
    }
}
