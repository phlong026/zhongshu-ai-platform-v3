-- A only. Explicitly opt in to classpath:db/migration/design-capability.
-- No identity account, session or consumer wallet is provisioned by this mapping.
CREATE TABLE design_capability_organization (
    caller_app_id varchar(80) NOT NULL,
    org_id bigint NOT NULL CHECK (org_id > 0),
    tenant_id bigint NOT NULL CHECK (tenant_id > 0),
    service_account_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 8000000000000000000)
        NOT NULL UNIQUE CHECK (service_account_id >= 8000000000000000000),
    active boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (caller_app_id, org_id)
);

CREATE TABLE design_capability_receipt (
    receipt_id varchar(36) PRIMARY KEY,
    caller_app_id varchar(80) NOT NULL,
    org_id bigint NOT NULL CHECK (org_id > 0),
    tenant_id bigint NOT NULL CHECK (tenant_id > 0),
    service_account_id bigint NOT NULL CHECK (service_account_id >= 8000000000000000000),
    operation varchar(64) NOT NULL,
    request_key varchar(200) NOT NULL,
    fingerprint char(64) NOT NULL,
    actor_json jsonb NOT NULL,
    payload_json jsonb NOT NULL,
    state varchar(16) NOT NULL CHECK (state IN ('PROCESSING', 'SUCCEEDED', 'FAILED', 'UNKNOWN')),
    result_json jsonb,
    job_id bigint,
    error_code integer,
    error_message text,
    lease_token varchar(36),
    lease_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (caller_app_id, org_id, operation, request_key)
);
CREATE INDEX design_capability_receipt_recovery ON design_capability_receipt(state, lease_until)
    WHERE state IN ('PROCESSING', 'UNKNOWN');
CREATE FUNCTION design_capability_receipt_scope_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.receipt_id,NEW.caller_app_id,NEW.org_id,NEW.tenant_id,NEW.service_account_id,NEW.operation,
           NEW.request_key,NEW.fingerprint,NEW.actor_json,NEW.payload_json)
       IS DISTINCT FROM ROW(OLD.receipt_id,OLD.caller_app_id,OLD.org_id,OLD.tenant_id,OLD.service_account_id,OLD.operation,
                            OLD.request_key,OLD.fingerprint,OLD.actor_json,OLD.payload_json) THEN
        RAISE EXCEPTION 'Capability receipt identity and business intent are immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER design_capability_receipt_scope_guard BEFORE UPDATE ON design_capability_receipt
    FOR EACH ROW EXECUTE FUNCTION design_capability_receipt_scope_immutable();
