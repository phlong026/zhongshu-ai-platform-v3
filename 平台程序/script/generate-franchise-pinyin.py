#!/usr/bin/env python3
"""Regenerate bundled CJK readings using an installed ICU uconv; no runtime dependency.

Usage: python3 script/generate-franchise-pinyin.py /path/to/icu/bin/uconv
ICU transliteration data: https://github.com/unicode-org/icu
Unicode/ICU license: https://www.unicode.org/license.txt
Readings are defaults; the onboarding form permits explicit polyphonic corrections.
"""
import pathlib
import subprocess
import sys

characters = [chr(code) for code in range(0x4E00, 0xA000)]
result = subprocess.run(
    [sys.argv[1], "-x", "Han-Latin; Latin-ASCII; Lower"],
    input="\n".join(characters), text=True, capture_output=True, check=True,
)
readings = result.stdout.splitlines()
if len(readings) != len(characters):
    raise RuntimeError("ICU output must preserve one reading per character")
rows = ["# ICU Han-Latin default readings; generated by script/generate-franchise-pinyin.py",
        "# Unicode data license: https://www.unicode.org/license.txt"]
for character, reading in zip(characters, readings):
    value = reading.strip()
    if value and value.isascii() and value.isalpha():
        rows.append(f"{ord(character):04x}\t{value}")
target = pathlib.Path(__file__).resolve().parents[1] / "platform/platform-org/src/main/resources/franchise-pinyin.tsv"
target.write_text("\n".join(rows) + "\n", encoding="utf-8")
print(f"Wrote {len(rows) - 2} default readings to {target}")
