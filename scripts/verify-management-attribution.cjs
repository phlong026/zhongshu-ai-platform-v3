const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const { A } = await require('./verify-owner-workbench.cjs').fixture();
  const attribution = require('../miniprogram/utils/commission-attribution');
  const B = require('../miniprogram/utils/business');
  const SF = require('../miniprogram/utils/sales-flow');
  const M = require('../miniprogram/pages/admin/model');
  const P = require('../miniprogram/utils/performance');
  const checks = [];
  const pass = name => { checks.push(name); console.log('PASS ' + name); };
  A.mutate(state => A.loginDemo(state, 'sales-dual'));
  const customer = B.add({ name: '责任归属测试', phone: '13900007801', source: '到店', city: '武汉市', summary: '设计委托责任归属' });
  B.write(customer.id, row => row.budgets.push({ version: 1, total: 300000, area: 300, parameters: { width: 10, depth: 15, floors: 2, area: 300 }, date: A.localDate() }), '保存预算', 'budget');
  SF.run(customer.id, 'commission-submit', { text: '两层住宅', scope: '全案设计', total: '12000', first: '6000', recipient: '总部', checked: true });
  const raw = () => wx.getStorageSync(B.KEY).customers.find(row => row.id === customer.id);
  const original = attribution.owner(raw());
  assert.equal(original, 'sales-dual');
  assert.equal(raw().serviceOrders.at(-1).responsibleId, original);
  pass('提交设计委托时保存原责任人与实际提交人');
  const storage = wx.getStorageSync(B.KEY);
  const moved = storage.customers.find(row => row.id === customer.id);
  moved.ownerId = 'liu';
  moved.owner = '刘业务';
  wx.setStorageSync(B.KEY, storage);
  assert.equal(attribution.owner(raw()), original);
  const fact = P.sourceRows(M.load()).find(row => row.id.startsWith('perf-commission:' + customer.id + ':'));
  assert.equal(fact.person, original);
  pass('当前责任人变更后历史委托绩效仍归发生时责任人');
  assert.equal(attribution.owner({ ownerId: 'current-owner', businessFlow: { submittedAt: '2026-10-01' }, serviceOrders: [{}] }), '');
  const historical = { ownerId: 'new-owner', businessFlow: { submittedAt: '2026-10-01T00:00:00Z' }, serviceOrders: [{}], responsibilityHistory: [{ from: 'old-owner', to: 'new-owner', effectiveAt: '2026-10-10T00:00:00Z' }] };
  assert.equal(attribution.owner(historical), 'old-owner');
  pass('旧数据只采用明确责任证据，缺证据不猜当前负责人');
  const O = require('../miniprogram/utils/organization');
  const book = { staff:[{id:'engineer-a',active:true,roles:['engineer']},{id:'inactive',active:false,roles:['engineer']}], managementSettings:{assignments:{engineering:'engineer-a'}} };
  assert.equal(O.defaultAssignee(book,'engineering'),'engineer-a');
  book.managementSettings.assignments.engineering='inactive';
  assert.equal(O.defaultAssignee(book,'engineering'),'');
  book.managementSettings.assignments.engineering='foreign';
  assert.equal(O.defaultAssignee(book,'engineering'),'');
  pass('新资料移交仅采用本组织在岗且岗位匹配的默认工程负责人');
  A.mutate(state => A.loginDemo(state, 'boss'));
  const boundary = wx.getStorageSync(B.KEY);
  const boundaryCustomer = boundary.customers.find(row=>row.id===customer.id);
  boundaryCustomer.businessFlow.submittedAt='2026-09-30T16:30:00.000Z';
  wx.setStorageSync(B.KEY,boundary);
  M.mutate(state=>{state.period='2026-10';});
  const W = require('../miniprogram/pages/admin/owner-model');
  const monthly = W.snapshot();
  assert(monthly.commissions.some(row=>row.id===customer.id), '北京时间十月一日的委托必须归入十月');
  const metrics = require('../miniprogram/pages/admin/owner-performance').build(monthly,'business').groups.flatMap(group=>group.rows).find(row=>row.id===original).metrics;
  assert.equal(metrics.find(row=>row.id==='commissionAmount').actual, monthly.commissions.filter(row=>attribution.owner(row)===original).reduce((sum,row)=>sum+row.serviceOrders.at(-1).total,0));
  pass('跨UTC月界的委托在首页和统一业务绩效中按北京时间归月');
  const dir = 'qa/management-completion-20261023';
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(dir + '/attribution-results.json', JSON.stringify({ result: 'passed', checks }, null, 2));
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
