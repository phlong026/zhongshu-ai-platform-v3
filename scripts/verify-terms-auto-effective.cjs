// 批次A2验收：合同收款约定生成即生效，老板分期审批全面下线
const assert=require('assert/strict');
let store={};
global.wx={getStorageSync:k=>store[k],setStorageSync:(k,v)=>{store[k]=JSON.parse(JSON.stringify(v));},removeStorageSync:k=>{delete store[k];},getStorageInfoSync:()=>({keys:Object.keys(store)})};
const A=require('../miniprogram/utils/account'),X=require('../miniprogram/utils/access');
const R=require('../miniprogram/utils/engineering-records');
const Ops=require('../miniprogram/utils/operations'),F=require('../miniprogram/utils/finance-source');
const file={name:'合同.pdf',sample:true};
const seed=()=>require('../miniprogram/utils/management-seed')();
const project=()=>({id:'prj-terms',projectId:'prj-terms',companyId:'quanzhou',name:'周建国家',city:'武汉',floors:2,manager:'张工程',managerId:'engineering-dual',customer:'周建国',image:'',events:[],corrections:[],rectifications:[],asOf:'',plan:{version:1,nodes:[{id:'n1',name:'基础工程',start:'2026-10-01',end:'2026-10-10',status:'待开工',milestone:''},{id:'n2',name:'主体封顶',start:'2026-10-11',end:'2026-10-30',status:'待开工',milestone:'topping'}]},materials:[],supplies:[],receipts:[],inspections:[],siteRecords:[],documents:[],sends:[],payments:[],collections:[],reships:[],planHistory:[],recordFlow:{version:1,materialPlans:[],warranties:[]}});
const install=p=>{const acct=store['zhongshu-account-v1'];store={};if(acct)store['zhongshu-account-v1']=acct;store['zhongshu-engineering-v1']={companyId:'quanzhou',projects:[p]};store['zhongshu-management-v1']=seed();};
const results=[],pass=n=>{results.push(n);console.log('PASS '+n);};
A.mutate(s=>A.loginDemo(s,'engineering-dual'));
install(project());
R.run('prj-terms','prepare',{total:'500000',first:'200000',file,note:'现场班组就绪，可以开工',workers:'3人'},0);
const book=F.merge(X.rawBook('quanzhou'));Ops.init(book);
const plan=book.operations.plans.find(q=>q.projectId==='prj-terms');
assert.ok(plan,'开工准备后应自动生成收款约定');
assert.equal(plan.status,'approved','登记合同后收款约定应生成即生效，当前为 '+plan.status);
pass('开工准备登记合同后，开工款封顶款收款约定生成即生效');
assert.deepEqual(plan.installments.map(i=>[i.name,i.amount,i.stage,i.due]),[['开工款',20000000,'start','2026-10-01'],['封顶款',30000000,'topping','2026-10-30']]);
pass('两期金额按合同总额与首期自动拆分，到期日取自施工节点');
A.mutate(s=>A.loginDemo(s,'boss'));
const pending=Ops.pending(F.merge(X.rawBook('quanzhou')));
assert.ok(!pending.some(t=>t.view==='plan-approval'),'老板待办不应再包含分期审批，实际：'+JSON.stringify(pending.map(t=>t.view)));
pass('老板待办不再出现合同分期审批事项');
const s2=F.merge(X.rawBook('quanzhou'));
assert.equal(Ops.apply(s2,'plan-approve','prj-terms',{}),null,'分期批准动作应已下线');
assert.equal(Ops.apply(s2,'plan-return','prj-terms',{}),null,'分期退回动作应已下线');
pass('分期批准与退回动作已下线');
const raw=JSON.parse(JSON.stringify(X.rawBook('quanzhou')));
raw.operations.plans.find(q=>q.projectId==='prj-terms').status='pending';
store['zhongshu-management-v1']=raw;
const s3=F.merge(X.rawBook('quanzhou'));
assert.equal(s3.operations.plans.find(q=>q.projectId==='prj-terms').status,'approved','历史待批分期应自动生效');
pass('历史待批分期数据自动迁移为已生效');
const gate=Ops.gate(F.merge(X.rawBook('quanzhou')),'prj-terms','start');
assert.equal(gate.configured,true);assert.equal(gate.required,20000000);
pass('开工收款闸门按已生效约定校验开工款');
console.log(results.length+' 项通过');
