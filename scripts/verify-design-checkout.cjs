const assert = require('assert/strict');
(async () => {
  const runtime = await require('./role-page-runtime.cjs').connect();
  const A = require('../miniprogram/utils/account');
  const B = require('../miniprogram/utils/business');
  const SF = require('../miniprogram/utils/sales-flow');
  const Pay = require('../miniprogram/utils/design-checkout');
  const login = (id, role) => { A.mutate(s => A.loginDemo(s, id)); if (role) A.mutate(s => A.switchIdentity(s, s.session.companyId, role)); };
  const raw = id => wx.getStorageSync(B.KEY).customers.find(c => c.id === id);
  login('hq-design-admin');
  assert.throws(() => Pay.savePricing({ rate: '0', scope: '全套施工图', recipient: '总部' }), /单价|金额/);
  Pay.savePricing({ rate: '20', scope: '全套施工图', recipient: '众墅之家总部', active: true });
  login('sales-dual', 'sales-lead');
  assert.throws(() => Pay.savePricing({ rate: '1' }), /总部设计/);
  const c = B.add({ name: '面积委托测试', phone: '13900008901', source: '门店到访', city: '武汉市', summary: '两层住宅' });
  const id = c.id;
  B.write(id, n => n.budgets.push({ version: 1, area: 400, parameters: { width: 12.5, depth: 16, floors: 2, area: 400 }, date: A.localDate() }), '保存参考预算', 'budget');
  const input = { paymentMode: 'area-full-demo-v1', text: '两层住宅', scope: '全套施工图', checked: true, __budgetVersion: 1, __pricingVersion: 1, total: '1' };
  assert.throws(() => SF.run(id, 'commission-submit', { ...input, __pricingVersion: 0 }), /计价已更新/);
  SF.run(id, 'commission-submit', input);
  const order = Pay.order(raw(id));
  assert.equal(order.amountCents, 800000);
  assert.equal(order.area, 400);
  assert.equal(order.status, 'pending');
  const incomplete = B.clone(raw(id));
  delete incomplete.businessFlow.paymentOrder;
  assert.equal(require('../miniprogram/utils/design-receipts').release(incomplete).ready, false);
  const forged = B.clone(raw(id));
  forged.businessFlow.paymentOrder.amountCents = 1;
  assert.equal(Pay.authorized(forged), false);
  forged.businessFlow.paymentOrder = { ...order, serviceVersion: 22 };
  assert.equal(Pay.authorized(forged), false);
  assert.equal(SF.next(raw(id)).view, 'pay');
  assert(!require('../miniprogram/utils/commercial-approval').tasks(raw(id)).length);
  const before = JSON.stringify(raw(id));
  assert.throws(() => SF.run(id, 'commission-pay', { channel: 'wechat', outcome: 'failed', orderId: order.id }), /失败/);
  assert.equal(JSON.stringify(raw(id)), before);
  login('hq-design-admin');
  assert.throws(() => SF.run(id, 'design-complete', { checked: true }), /支付/);
  assert.throws(() => SF.run(id, 'commission-pay', { channel: 'wechat', outcome: 'success', orderId: order.id }), /权限/);
  Pay.savePricing({ rate: '25', scope: '全套施工图', recipient: '众墅之家总部', active: true });
  login('sales-dual', 'sales-lead');
  const originalInfo = wx.getAccountInfoSync;
  wx.getAccountInfoSync = () => ({ miniProgram: { envVersion: 'release' } });
  assert.throws(() => SF.run(id, 'commission-pay', { channel: 'wechat', outcome: 'success', orderId: order.id }), /体验|模拟/);
  wx.getAccountInfoSync = originalInfo;
  SF.run(id, 'commission-pay', { channel: 'wechat', outcome: 'success', orderId: order.id });
  assert(Pay.paid(raw(id)));
  assert.equal(Pay.order(raw(id)).amountCents, 800000, '计价变更不能修改已生成订单');
  assert.equal(SF.next(raw(id)).view, 'complete');
  const paidAt = Pay.order(raw(id)).paidAt;
  const paidRevision = raw(id).revision;
  assert.throws(() => SF.run(id, 'commission-pay', { channel: 'alipay', outcome: 'success', orderId: order.id }), /已完成|已支付/);
  assert.throws(() => SF.run(id, 'commission-pay', { channel: 'invalid', outcome: 'failed', orderId: order.id }), /已完成|已支付/);
  assert.equal(raw(id).revision, paidRevision);
  assert.equal(Pay.order(raw(id)).paidAt, paidAt);
  assert.equal(Pay.order(raw(id)).channel, 'wechat');
  wx.reLaunch({ url: SF.url(id, 'pay') });
  assert.equal(await (await runtime.currentPage()).$('button[data-channel="wechat"]'), null, '已支付订单不能再显示付款渠道或失败模拟操作');
  login('hq-design-admin');
  assert(SF.tasks().some(t => t.customerId === id && t.action === '登记设计完成'));
  SF.run(id, 'design-complete', { checked: true });
  assert.equal(SF.next(raw(id)).view, 'dispatch');
  const f = name => ({ name: name + '.pdf', sample: true, text: id + ' V1', meta: { customerId: id, projectId: raw(id).projectId, version: 'V1' } });
  const dispatch = { recipient: '李业务', note: '本版正式成果', checked: true, drawingVersion: 'V1', resultFile: f('成果'), drawingFile: f('施工图'), reviewFile: f('审核依据') };
  assert.throws(() => SF.run(id, 'design-dispatch', { ...dispatch, drawingFile: null }), /施工图|文件|补齐/);
  assert.throws(() => SF.run(id, 'design-dispatch', { ...dispatch, drawingFile: { name: '不明施工图.pdf', path: '/other-project/drawing.pdf' } }), /模拟文件|项目|版本/);
  assert.throws(() => SF.run(id, 'design-dispatch', { ...dispatch, drawingFile: { ...f('错项目施工图'), meta: { customerId: id, projectId: 'other-project', version: 'V1' } } }), /项目|版本/);
  SF.run(id, 'design-dispatch', dispatch);
  login('sales-dual', 'sales-lead');
  assert(SF.tasks().some(t => t.customerId === id && t.action === '移交给工程'));
  const packet = { ...dispatch, dispatchVersion: 1, confirmationFile: f('客户确认'), confirmationDate: A.localDate(), received: true, confirmed: true };
  assert.throws(() => SF.run(id, 'packet-submit', { ...packet, drawingFile: f('其他版本') }), /下发|版本/);
  SF.run(id, 'packet-submit', packet);
  login('engineering-dual', 'project-manager');
  assert(SF.tasks().some(t => t.customerId === id && t.action === '核对接收'));
  SF.run(id, 'packet-receive', { checked: true });
  assert(raw(id).acceptance);
  console.log('PASS 面积计价、版本锁定、模拟支付门禁、幂等、总部设计文件与业务工程接续');
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
