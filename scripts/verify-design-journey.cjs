const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const runtime = await require('./role-page-runtime.cjs').connect();
  const A = require('../miniprogram/utils/account'), B = require('../miniprogram/utils/business'), SF = require('../miniprogram/utils/sales-flow');
  const rows = JSON.parse(fs.readFileSync('qa/design-checkout-20261023/initial-state.json'));
  for (const [key, value] of rows) wx.setStorageSync(key, value);
  const id = wx.getStorageSync(B.KEY).customers.find(c => /微信支付闭环/.test(c.name)).id;
  const login = (who, role) => { A.mutate(s => A.loginDemo(s, who)); if (role) A.mutate(s => A.switchIdentity(s, s.session.companyId, role)); };
  const page = () => getCurrentPages().at(-1);
  const raw = () => wx.getStorageSync(B.KEY).customers.find(c => c.id === id);
  const control = async selector => { const e = await (await runtime.currentPage()).$(selector); assert(e, selector); return e; };
  const tap = async selector => (await control(selector)).tap();
  const check = async key => (await control('checkbox-group[data-key="' + key + '"]')).trigger('change', { value: ['yes'] });
  const open = view => wx.reLaunch({ url: SF.url(id, view) });
  login('sales-dual', 'sales-lead'); open('submit');
  await control('.journey-quote');
  await (await control('textarea[data-key="text"]')).input('两层乡墅，老人房和露台按本版预算尺寸设计');
  await check('checked'); await tap('.journey-submit');
  assert.equal(page().data.view, 'pay'); assert.equal(raw().businessFlow.paymentOrder.status, 'pending');
  assert.equal(await (await runtime.currentPage()).$('button[data-outcome="failed"]'), null);
  await tap('button[data-channel="alipay"]'); await tap('.journey-pay');
  assert.equal(page().data.cashier.channel, 'alipay'); assert(page().data.cashier.open);
  assert.equal(raw().businessFlow.paymentOrder.status, 'pending', '打开收银台不能直接支付');
  await tap('.cashier-close'); assert.equal(page().data.cashier.open, false);
  await tap('button[data-channel="wechat"]'); await tap('.journey-pay');
  assert.equal(page().data.cashier.channel, 'wechat');
  const saveStorage=wx.setStorageSync; let failOnce=true; const beforeFailure=JSON.stringify(raw());
  wx.setStorageSync=(key,value)=>{if(key===B.KEY&&failOnce){failOnce=false;throw Error('保存未完成，请重试');}return saveStorage(key,value);};
  await tap('.cashier-confirm'); wx.setStorageSync=saveStorage;
  assert.equal(page().data.cashier.open,false,'支付保存失败应退出收银台并明确提示');
  assert.equal(JSON.stringify(raw()),beforeFailure,'保存失败不能记为已付款或产生待办');
  await control('.journey-error'); await tap('.journey-pay');
  await tap('.cashier-confirm');
  assert.equal(page().data.view, 'paid'); assert.equal(raw().businessFlow.paymentOrder.status, 'paid');
  const revision = raw().revision; open('pay');
  assert.equal(await (await runtime.currentPage()).$('.journey-pay'), null); assert.equal(raw().revision, revision);
  for (const who of ['finance-dual','hq-finance-dual']) {
    login(who,'finance'); wx.reLaunch({url:'/pages/account/index?view=messages'});
    const message=page().data.messages.find(row=>row.objectId===id&&row.payment); assert(message);
    await tap('button[data-customer="'+id+'"]'); assert.equal(page().data.paymentReceipt.method,raw().businessFlow.paymentOrder.paymentMethod);
    await tap('.payment-receipt-close');
  }
  login('hq-design-admin'); open('complete');
  await tap('.journey-generate');
  assert(page().data.form.resultFile.meta.projectId === raw().projectId);
  assert(page().data.form.drawingFile.previewKind === 'drawing');
  await tap('button[data-preview-key="drawingFile"]'); assert(page().data.documentPreview.image);
  let zoomed=null; const previousPreview=wx.previewImage; wx.previewImage=options=>{zoomed=options;};
  await tap('.document-image'); assert.equal(zoomed.urls[0],page().data.documentPreview.image); wx.previewImage=previousPreview;
  await tap('.document-close');
  await check('checked'); await tap('.journey-complete');
  assert.equal(page().data.view, 'dispatch'); assert(page().data.form.drawingFile);
  await check('checked'); await tap('.journey-dispatch');
  assert(raw().businessFlow.dispatch);
  login('sales-dual', 'sales-lead'); open('handover');
  assert.deepEqual(page().data.form.drawingFile, raw().businessFlow.dispatch.drawingFile);
  await tap('.journey-client-confirm'); await tap('.client-confirm-primary');
  assert(page().data.form.confirmationFile.meta.customerId === id);
  await (await control('textarea[data-key="note"]')).input('客户确认本版图纸，现场边界与入场道路已交底。');
  await check('received'); await tap('.journey-handover');
  login('engineering-dual', 'project-manager'); open('receive'); await check('checked'); await tap('.journey-receive');
  assert.equal(page().data.view, 'created');
  const projectId = page().data.journey.engineeringId; assert(projectId);
  await tap('.journey-open-project');
  assert.equal(page().route, 'pages/build/record/index'); assert.equal(page().data.p.id, projectId);
  const project = wx.getStorageSync('zhongshu-engineering-v1').projects.find(p => p.id === projectId);
  assert.equal(project.documents.length, 5); assert.equal(project.projectId, raw().projectId);
  console.log('PASS 可视委托、双渠道收银台取消/确认、成果预览、同版移交与工程建项入口');
})().catch(e => { console.error(e.stack); process.exitCode = 1; });
