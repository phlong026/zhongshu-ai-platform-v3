// 进度偏差与逾期预警：未完成节点对照计划结束日显示剩余/逾期天数，
// 已完成节点显示提前/超期完成；工程首页和项目列表汇总逾期节点数。
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
(async()=>{
 const runtime=await require('./role-page-runtime.cjs').connect(),out=path.resolve('qa/engineering-schedule-pace-20261028');fs.mkdirSync(out,{recursive:true});
 const A=require('../miniprogram/utils/account'),E=require('../miniprogram/pages/build/model'),R=require('../miniprogram/utils/engineering-records'),W=require('../miniprogram/pages/build/workbench');
 const scenes=JSON.parse(fs.readFileSync('qa/engineering-records-20261021/page-scenes.json','utf8'));const seed=scenes.find(s=>s.action==='site').before;for(const[k,v]of seed)wx.setStorageSync(k,v);
 const checks=[],pass=n=>{checks.push(n);console.log('PASS '+n);};
 A.mutate(s=>A.loginDemo(s,'manager-li'));A.mutate(s=>A.switchIdentity(s,'quanzhou','engineer'));
 const KEY='zhongshu-engineering-v1';
 const shift=n=>{const t=new Date();t.setDate(t.getDate()+n);return t.toISOString().slice(0,10);};
 const mutate=fn=>{const st=wx.getStorageSync(KEY);fn(st.projects.find(p=>p.recordFlow));wx.setStorageSync(KEY,st);};
 const pid=wx.getStorageSync(KEY).projects.find(p=>p.recordFlow).id;
 const today=shift(0);
 mutate(p=>{p.plan.nodes[0].end=shift(-1);p.plan.nodes[0].start=shift(-10);});
 let pr=R.progress(R.get(pid));
 assert.equal(pr.overdue,1,'逾期节点计数');assert.equal(pr.rows[0].text,'已逾期1天','逾期文案');
 assert(pr.rows.slice(1).every(r=>!/^已逾期/.test(r.text)),'其余待开工节点未逾期');
 pass('未完成节点按计划结束日计算逾期天数');
 mutate(p=>{p.plan.nodes[0].status='已完成';p.plan.nodes[0].completedAt=shift(-3);});
 pr=R.progress(R.get(pid));assert.equal(pr.rows[0].text,'提前2天完成','计划昨日结束、提前两日完成');
 mutate(p=>{p.plan.nodes[0].completedAt=shift(1);});pr=R.progress(R.get(pid));assert.equal(pr.rows[0].text,'超期2天完成','晚于计划完成显示超期');
 pass('已完成节点显示提前或超期天数');
 mutate(p=>{p.plan.nodes.forEach((n,i)=>{n.status=i?'待开工':'施工中';delete n.completedAt;n.start=shift(-10);n.end=i?shift(60):shift(6);});});
 pr=R.progress(R.get(pid));assert.equal(pr.rows[0].text,'剩6天','临近到期提示剩余天数');assert.equal(pr.dueSoon,1);
 mutate(p=>{p.plan.nodes[0].end=shift(30);});pr=R.progress(R.get(pid));assert.equal(pr.rows[0].text,'','远期节点不提示');
 mutate(p=>{p.plan.nodes[0].end=shift(-1);});
 wx.reLaunch({url:R.link(R.get(pid),'overview')});let page=getCurrentPages().at(-1);assert(!page.data.error,page.data.error);
 assert.equal(page.data.nodeRows[0].pace,'已逾期1天','节点行显示偏差');assert.equal(page.data.paceOverdue,1);assert(page.data.paceDone<page.data.paceTotal);
 assert(await(await runtime.currentPage()).$('.eng-tag.tone-danger'),'渲染逾期红色标签');
 pass('项目施工进度页逐节点显示偏差并高亮逾期');
 wx.reLaunch({url:'/pages/build/home/index'});page=getCurrentPages().at(-1);
 const stat=page.data.eng.stats.find(s=>s.label==='逾期节点');assert(stat&&stat.value===1,'首页统计逾期节点');
 assert.equal(page.data.eng.cards.find(c=>c.id===pid).overdue,1,'项目卡片携带逾期数');
 pass('工程首页统计逾期节点并汇总到项目卡片');
 wx.reLaunch({url:'/pages/build/projects/index?filter=在建'});page=getCurrentPages().at(-1);
 const card=page.data.cards.find(c=>c.id===pid);assert(card&&card.pace==='已逾期1天','项目列表显示当前节点偏差');
 pass('项目列表卡片显示当前节点偏差');
 mutate(p=>{p.delivery={date:today,status:'已交付'};});
 const delivered=W.card(E.load().projects.find(x=>x.id===pid));assert.equal(delivered.overdue,0,'已交付项目不再计逾期');
 pass('已交付项目不计入逾期');
 fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({result:'passed',checks,projectId:pid,evidence:'Node Page/WXML integration with schedule pace rendering'},null,2));console.log('COMPLETE',checks.length,'checks');
})().catch(e=>{console.error(e.stack);fs.writeFileSync(path.resolve('qa/engineering-schedule-pace-20261028/results.json'),JSON.stringify({result:'failed',error:e.message},null,2));process.exitCode=1;});
